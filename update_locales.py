def parse_locale(text):
    """Parse locale.cfg text into {"section/key": value}, preserving order."""
    entries = {}
    section = None
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        section_match = re.match(r"^\[([^\]]+)\]$", stripped)
        if section_match:
            section = section_match.group(1)
            continue
        kv_match = re.match(r"^([^=]+)=(.*)$", line)
        if kv_match and section:
            entries[f"{section}/{kv_match.group(1).strip()}"] = kv_match.group(2)
    return entries


def render_locale(en_text, translations, disclaimer):
    """Rebuild a language file mirroring the English file's exact layout.

    Every section header, blank line, and key from the English file appears in
    the same position; only the values are replaced. This guarantees the
    structural parity the locale tests require.
    """
    out = [f"# {disclaimer}", ""]
    section = None
    for line in en_text.splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            continue
        if not stripped:
            out.append("")
            continue
        section_match = re.match(r"^\[([^\]]+)\]$", stripped)
        if section_match:
            section = section_match.group(1)
            out.append(stripped)
            continue
        kv_match = re.match(r"^([^=]+)=(.*)$", line)
        if kv_match and section:
            key = kv_match.group(1).strip()
            out.append(f"{key}={translations[f'{section}/{key}']}")
    # Collapse any accidental double blank lines at the end
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


def sanitize_value(value):
    """Normalize a model-produced value into a single valid cfg line."""
    value = value.replace("\r", "").replace("\n", "\\n").replace("\t", " ")
    return value.strip()


